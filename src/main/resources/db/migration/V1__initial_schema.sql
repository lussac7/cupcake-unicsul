-- PRODUCTS
CREATE TABLE products
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name        VARCHAR(150)  NOT NULL,
    description TEXT          NOT NULL,
    price       NUMERIC(10,2) NOT NULL,
    image_url   VARCHAR(500),
    active      BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_products PRIMARY KEY (id),
    CONSTRAINT ck_products_name CHECK (TRIM(name) <> ''),
    CONSTRAINT ck_products_description CHECK (TRIM(description) <> ''),
    CONSTRAINT ck_products_price CHECK (price > 0)
);

-- ORDERS
CREATE TABLE orders
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    customer_name    VARCHAR(150) NOT NULL,
    customer_email   VARCHAR(254) NOT NULL,
    delivery_address TEXT          NOT NULL,
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    total            NUMERIC(12,2) NOT NULL,

    CONSTRAINT pk_orders PRIMARY KEY (id),
    CONSTRAINT ck_orders_customer_name CHECK (TRIM(customer_name) <> ''),
    CONSTRAINT ck_orders_customer_email CHECK (TRIM(customer_email) <> ''),
    CONSTRAINT ck_orders_delivery_address CHECK (TRIM(delivery_address) <> ''),
    CONSTRAINT ck_orders_total CHECK (total > 0)
);

-- ORDER ITEMS
CREATE TABLE order_items
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_id     BIGINT        NOT NULL,
    product_id   BIGINT        NOT NULL,
    product_name VARCHAR(150)  NOT NULL,
    unit_price   NUMERIC(10,2) NOT NULL,
    quantity     INTEGER       NOT NULL,
    subtotal     NUMERIC(12,2) NOT NULL,

    CONSTRAINT pk_order_items PRIMARY KEY (id),

    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id)
        REFERENCES orders (id) ON DELETE RESTRICT,

    CONSTRAINT fk_order_items_product FOREIGN KEY (product_id)
        REFERENCES products (id) ON DELETE RESTRICT,

    CONSTRAINT uq_order_items_order_product UNIQUE (order_id, product_id),

    CONSTRAINT ck_order_items_product_name CHECK (TRIM(product_name) <> ''),
    CONSTRAINT ck_order_items_unit_price CHECK (unit_price > 0),
    CONSTRAINT ck_order_items_quantity CHECK (quantity > 0),
    CONSTRAINT ck_order_items_subtotal CHECK (subtotal = unit_price * quantity)
);

-- INDEXES
CREATE INDEX idx_products_active_name
    ON products (name)
    WHERE active = TRUE;

CREATE INDEX idx_order_items_product_id
    ON order_items (product_id);

CREATE INDEX idx_orders_created_at
    ON orders (created_at);
